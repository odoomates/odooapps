VERSION = release.version_info[0]

def question(key, topic, text, options, right, why, needs=None):
    """ A question of the quiz, in a topic: 'odoo', 'fields' or 'built'. A question
    on what the learner built needs a step done: (course key or family, step key). """
    return {'key': key, 'topic': topic, 'question': text, 'options': options, 'right': right,
            'why': why, 'needs': needs}


